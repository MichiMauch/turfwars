        const LatLng(47.0000, 8.0000),
        const LatLng(47.0003, 8.0000),
        const LatLng(47.0003, 8.0004),
        const LatLng(47.0000, 8.0004),
        const LatLng(47.0000, 8.0000),
      ];
      expect(WalkSimulator.densify(square).length, greaterThan(10));
    });

    test('lässt zu wenige Punkte unverändert', () {
      final one = [const LatLng(47, 8)];
      expect(WalkSimulator.densify(one), one);
    });
