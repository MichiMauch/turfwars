    test('trifft die Fläche, die turf auf dem Server rechnet', () {
      final mine = polygonAreaSqm(_productionRing);
      expect((mine - _turfAreaSqm).abs() / _turfAreaSqm, lessThan(0.001));
    });

    test('ein zu kurzer Ring hat keine Fläche', () {
      expect(polygonAreaSqm([const LatLng(47, 8), const LatLng(47.001, 8)]), 0);
    });
  });

  group('WalkSimulator.densify', () {
    test('legt Zwischenpunkte, bis der Abstand unter 5 m liegt', () {
      // Rund 111 m je 0.001 Grad Breite.
      final coarse = [
        const LatLng(47.0000, 8.0),
        const LatLng(47.0010, 8.0),
      ];
      final dense = WalkSimulator.densify(coarse);

      const distance = Distance();
      for (int i = 1; i < dense.length; i++) {
        expect(
          distance.as(LengthUnit.Meter, dense[i - 1], dense[i]),
          lessThanOrEqualTo(5.0001),
        );
      }
      expect(dense.first, coarse.first);
      expect(dense.last, coarse.last);
    });

    test('eine mit vier Ecken getippte Runde kommt über MIN_TRACK_POINTS', () {
      // Kleinstmögliche brauchbare Runde: rund 120 m Umfang.
